// GET ALL CUSTOMERS (ADMIN)
export const getAllCustomers = async (req, res) => {
    try {
        const customers = await User.find({ role: "customer" })
            .select("-password")
            .sort({ createdAt: -1 });

        res.status(200).json({
            success: true,
            totalCustomers: customers.length,
            customers
        });

    } catch (error) {
        res.status(500).json({
            success: false,
            message: error.message
        });
    }
};